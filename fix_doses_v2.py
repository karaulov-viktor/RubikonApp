def main():
    if not os.path.exists(DB):
        print('НЕ НАЙДЕНА БАЗА:', os.path.abspath(DB))
        print('Запустите скрипт из корня проекта (там, где папка data).')
        sys_exit(1)

    conn = sqlite3.connect(DB)
    cur = conn.cursor()

    # бэкап
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M')
    backup = DB.replace('.db', f'_backup_{stamp}.db')
    shutil.copy2(DB, backup)
    print(f'[бэкап] {backup}\n')

    rows = cur.execute('SELECT rowid, name FROM drugs').fetchall()
    free = {r[0]: r[1].lower() for r in rows}   # rowid -> имя (нижний регистр)

    changed = 0
    problems = []

    for keys, excl, fields in RULES:
        hits = [rid for rid, name in free.items()
                if all(k in name for k in keys) and not any(x in name for x in excl)]
        if len(hits) != 1:
            problems.append((keys, excl, len(hits)))
            continue
        rid = hits.pop()
        del free[rid]
        name = cur.execute('SELECT name FROM drugs WHERE rowid=?', (rid,)).fetchone()[0]

        cur_vals = cur.execute(
            'SELECT dose_per_kg, concentration, dose_unit, tab_mg, form, duration_days '
            'FROM drugs WHERE rowid=?', (rid,)).fetchone()
        new_vals = []
        for old, new in zip(cur_vals, fields):
            new_vals.append(old if new is None else new)
        if tuple(new_vals) == tuple(cur_vals):
            print(f'  = {name[:45]:<45} уже актуально')
            continue
        cur.execute(
            'UPDATE drugs SET dose_per_kg=?, concentration=?, dose_unit=?, tab_mg=?, form=?, '
            'duration_days=? WHERE rowid=?', (*new_vals, rid))
        changed += 1
        d, c, u, t, f, dd = new_vals
        print(f'  * {name[:45]:<45} доза={d} конц={c} ед={u} таб={t} форма={f} курс={dd} дн')

    conn.commit()

    print(f'\nИзменено: {changed}')
    if problems:
        print('⚠ Не найдено однозначного совпадения (проверьте вручную):')
        for keys, excl, n in problems:
            print(f'   {keys} (искл.: {excl}) -> совпадений: {n}')

    print('\n--- ИТОГОВАЯ СВОДКА (все 61) ---')
    print(f'{"#":>2} | {"Наименование":<40} | {"доза":>6} | {"конц":>6} | '
          f'{"ед":<10} | {"табл":>6} | {"форма":<9} | курс')
    for i, (name, d, c, u, t, f, dd) in enumerate(cur.execute(
            'SELECT name, dose_per_kg, concentration, dose_unit, tab_mg, form, duration_days '
            'FROM drugs ORDER BY rowid'), 1):
        flag = '  <-- ПРОВЕРИТЬ' if (u not in ('none',) and not d) else ''
        print(f'{i:>2} | {name[:40]:<40} | {d:>6} | {c:>6} | {u or "":<10} | '
              f'{t:>6} | {f or "":<9} | {dd} дн{flag}')
    conn.close()


def sys_exit(code):
    raise SystemExit(code)


if __name__ == '__main__':
    main()
