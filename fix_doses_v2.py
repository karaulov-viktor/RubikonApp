    # Стимулонг: доза НА ЖИВОТНОЕ, не на кг! Собаки 0,5-5 мл, кошки 0,5-2,5 мл, 4-5 дней
    (['стимулонг'],                    [], (0.5,  None,  'per_animal', 0, None,       5)),
    # Триметокс таблетки: 1 таб (сульфадимидин 400 мг + триметоприм 80 мг) на 10 кг,
    # 2 раза в сутки, 5-7 дней  ->  0,1 таб/кг
