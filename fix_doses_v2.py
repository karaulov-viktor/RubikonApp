    # беназеприл 0,25-0,5 мг/кг; tab_mg = содержание БЕНАЗЕПРИЛА (2,5/5/10) — верно, доза была занижена
    (['бикардил', '10'],               [], (0.25, None,  None,    10.0, None,        None)),
    (['бикардил', '2,5'],              [], (0.25, None,  None,    2.5,  None,        None)),
