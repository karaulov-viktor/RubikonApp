# Что обновляем: (фрагмент названия в БД, новый текст)
EXAMPLES = [
    ("Азитрикон", AZITRICON),
    ("Кетопрофен", KETOPROFEN),
]


def find_drugs_table(cur):
    """Находим таблицу препаратов: в ней должны быть колонки name и instruction."""
    cur.execute("SELECT name FROM sqlite_master WHERE type='table'")
    tables = [r[0] for r in cur.fetchall()]
    for table in tables:
        if table.startswith("sqlite_"):
            continue
        cur.execute(f"PRAGMA table_info({table})")
        cols = {row[1].lower() for row in cur.fetchall()}
        if "name" in cols and "instruction" in cols:
            return table
    return None


def main():
    db_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join("data", "rubikon.db")
    if not os.path.exists(db_path):
        print(f"[FAIL] база не найдена: {db_path}")
        print("       Запустите скрипт из корня проекта или укажите путь аргументом.")
        sys.exit(1)

    # Резервная копия базы — прежде чем что-то менять.
    # Откат: просто удалите новую версию и переименуйте .bak-... обратно.
    #
    # ВАЖНО: используем copyfile, а НЕ copy2. copy2 копирует ещё и
    # метаданные (время файла), а на USB-флешке FAT32/exFAT, смонтированной
    # в WSL через drvfs, это падает: PermissionError: Operation not permitted.
    # copyfile копирует только содержимое — на флешке работает.
    stamp = time.strftime("%Y%m%d-%H%M%S")
    backup_path = f"{db_path}.bak-{stamp}"
    n = 1
    while os.path.exists(backup_path):   # повторный запуск за ту же секунду
        backup_path = f"{db_path}.bak-{stamp}-{n}"
        n += 1
    shutil.copyfile(db_path, backup_path)
    print(f"[OK ] резервная копия базы: {backup_path}")

    con = sqlite3.connect(db_path)
    cur = con.cursor()

    table = find_drugs_table(cur)
    if not table:
        print("[FAIL] не нашёл таблицу с колонками name + instruction")
        sys.exit(1)
    print(f"[OK ] таблица препаратов: {table}")

    for name_fragment, text in EXAMPLES:
        cur.execute(
            f"UPDATE {table} SET instruction = ? WHERE name LIKE ?",
            (text, f"%{name_fragment}%"),
        )
        updated = cur.rowcount
        if updated == 0:
            print(f"[WARN] «{name_fragment}» не найден в БД — проверьте название")
        else:
            first_line = text.split("\n", 1)[1 if "\n" in text else 0][:48]
            print(f"[OK ] «{name_fragment}»: обновлено строк {updated}, "
                  f"длина текста {len(text)} знаков, начало: {first_line!r}")

    con.commit()
    con.close()
    print("\nГотово. Запустите приложение и откройте карточку препарата —")
    print("заголовки секций будут зелёными, ограничения — красными.")


if __name__ == "__main__":
    main()
