# -*- coding: utf-8 -*-
"""
Токены бело-зелёной темы RubikonApp. ЕДИНСТВЕННОЕ место, где заданы цвета.

Меняешь значение здесь — перекрашивается весь интерфейс:
  - kv-файлы:  #:import T models.theme   ->  md_bg_color: T.CARD
  - py-файлы:  from models import theme as T  ->  md_bg_color=T.CARD

Значения — ГОТОВЫЕ КОРТЕЖИ Kivy (get_color_from_hex), потому что их
используют и новые экраны спринта «Питомцы», и старые экраны
(каталог, лечение, календарь), которые писались под кортежи.

Брендовый зелёный #177300 зафиксирован ТОЛЬКО здесь.
PALETTE_VERSION меняется при любой правке цветов (для чекпоинтов).
"""
from kivy.utils import get_color_from_hex as _h

# --- Поверхности ---
BG = _h("#FFFFFF")            # фон экранов (белый — п.7 ТЗ)
CARD = _h("#FFFFFF")          # карточки белые
CARD_BORDER = _h("#E3EDE0")   # обводка карточек (лёгкий зелёный оттенок)

# --- Фирменный зелёный ---
GREEN = _h("#177300")         # акценты, заголовки, активные пункты меню
GREEN_DARK = _h("#125C00")    # нажатое состояние, тень акцентов
GREEN_SOFT = _h("#E9F4E4")    # мягкие подложки, чипы, дни с событиями

# --- Совместимость со старыми экранами (спринты 1-2.6) ---
# Старые экраны импортируют PRIMARY / PRIMARY_DARK / PRIMARY_SOFT /
# MINT_BG / MINT_TEXT — раньше это был бирюзовый #1F7F9C.
# Теперь те же роли играют фирменным зелёным: старые экраны
# перекрашиваются автоматически, код старых экранов НЕ менялся.
PRIMARY = GREEN
PRIMARY_DARK = GREEN
PRIMARY_SOFT = GREEN_SOFT
MINT_BG = GREEN_SOFT
MINT_TEXT = GREEN

# --- Текст ---
TEXT_MAIN = _h("#1F2A1C")     # основной текст
TEXT_SUB = _h("#7C8A76")      # вторичный текст (подписи, подзаголовки)

# --- Служебные ---
WHITE = _h("#FFFFFF")
DANGER = _h("#C62828")        # удаление, предупреждения

# --- Дисклеймер (янтарный, как в старых экранах) ---
AMBER_BG = _h("#FFF6E8")
AMBER_ICON = _h("#C0902E")
AMBER_TEXT = _h("#8A6A33")

PALETTE_VERSION = "whitegreen-2"
