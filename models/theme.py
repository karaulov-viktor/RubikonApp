# -*- coding: utf-8 -*-
"""
Токены бело-зелёной темы RubikonApp. ЕДИНСТВЕННОЕ место, где заданы цвета.

Меняешь значение здесь — перекрашивается весь интерфейс:
  - kv-файлы:  #:import T models.theme   ->  md_bg_color: T.CARD
  - py-файлы:  from models import theme as T  ->  md_bg_color=T.CARD

Значения — ГОТОВЫЕ КОРТЕЖИ Kivy (get_color_from_hex), потому что их
используют и новые экраны спринта «Питомцы», и старые экраны
(каталог, лечение, календарь), которые писались под кортежи.

Палитра whitegreen-4 (выбор владельца, 2026-09-14):
  ПРИЛОЖЕНИЕ БЕЛОЕ, ШРИФТЫ ТЁМНО-ЗЕЛЁНЫЕ.
  Бирюзовые и мятные тона убраны полностью:
  - GREEN_SOFT больше не «мятная заливка», а почти белая нейтральная
    подложка (едва отличима от белого, только чтобы карточка читалась);
  - текст — тёмно-зелёный вместо почти чёрного;
  - акцент — глубокий тёмно-зелёный (#14532D) вместо травяного
    #177300, который читался как «лязгающий» яркий.

PALETTE_VERSION меняется при любой правке цветов (для чекпоинтов).
При старте main.py печатает в консоль строку
  [RubikonApp] тема whitegreen-4
Если версия другая (или её нет) — у вас устаревший theme.py.
"""
from kivy.utils import get_color_from_hex as _h

# --- Поверхности ---
BG = _h("#FFFFFF")            # фон экранов (белый)
CARD = _h("#FFFFFF")          # карточки белые
CARD_BORDER = _h("#DDE6DA")   # обводка карточек (нейтральный серо-зелёный)

# --- Фирменный тёмно-зелёный ---
GREEN = _h("#14532D")         # акценты, заголовки, активные пункты меню
GREEN_DARK = _h("#0D3A1E")    # нажатое состояние, фон тостов
GREEN_SOFT = _h("#F1F5EF")    # почти белая нейтральная подложка
                              # ( НЕ мятная! чипы, дни с событиями )

# --- Совместимость со старыми экранами (спринты 1-2.6) ---
# Старые экраны импортируют PRIMARY / PRIMARY_DARK / PRIMARY_SOFT /
# MINT_BG / MINT_TEXT — имена исторические, роли прежние:
# PRIMARY = акцент, *_SOFT/*_BG = мягкая подложка. Код старых экранов
# НЕ менялся — перекрашивается автоматически.
PRIMARY = GREEN
PRIMARY_DARK = GREEN
PRIMARY_SOFT = GREEN_SOFT
MINT_BG = GREEN_SOFT
MINT_TEXT = GREEN

# --- Текст (тёмно-зелёные шрифты — выбор владельца) ---
TEXT_MAIN = _h("#1B3A28")     # основной текст — тёмно-зелёный
TEXT_SUB = _h("#5E7263")      # вторичный текст (приглушённый зелёно-серый)

# --- Служебные ---
WHITE = _h("#FFFFFF")
DANGER = _h("#C62828")        # удаление, предупреждения

# --- Дисклеймер (янтарный, как в старых экранах) ---
AMBER_BG = _h("#FFF6E8")
AMBER_ICON = _h("#C0902E")
AMBER_TEXT = _h("#8A6A33")

PALETTE_VERSION = "whitegreen-4"
